// 生成键盘扩展专用的精简词库 PinyinKit/ResourcesKeyboard/lexicon.json
//
// 为什么要精简：
//   完整词库存量 4.8MB / 12 万条（2.67 万单字 + 9.6 万词组）。键盘扩展的系统内存上限
//   只有几十 MB（jetsam 直接杀进程，和广播扩展同一套机制），解码峰值 + 常驻索引叠加
//   很容易顶到上限；而键盘实际只用到高频词。这里按频率保留前 4 万词组，单字全留
//   （单字是兜底候选，砍了会明显变难用）。
//
// 用法：node tools/build-keyboard-lexicon.mjs
// 产物：PinyinKit/ResourcesKeyboard/lexicon.json（入库；词库源变动后重跑）

import { readFileSync, writeFileSync, mkdirSync, statSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const fullPath = join(root, 'PinyinKit', 'Resources', 'lexicon.json')
const outDir = join(root, 'PinyinKit', 'ResourcesKeyboard')
const outPath = join(outDir, 'lexicon.json')

/** 保留的词组条数（按频率从高到低） */
const WORD_LIMIT = 40000

const full = JSON.parse(readFileSync(fullPath, 'utf8'))

if (!Array.isArray(full.chars) || !Array.isArray(full.words)) {
  throw new Error('lexicon.json 结构不对：缺少 chars / words 数组')
}

// 按频率取前 N 条的「下标集合」，再按原始顺序输出：
// 保持原顺序可以保证同分候选的排序与完整词库完全一致（引擎只比 score）。
const sortedIdx = full.words
  .map((w, i) => ({ i, f: w.f ?? 0 }))
  .sort((a, b) => b.f - a.f)
  .slice(0, WORD_LIMIT)
  .map((x) => x.i)

const keep = new Set(sortedIdx)
const words = full.words.filter((_, i) => keep.has(i))

const trimmed = {
  version: full.version,
  source: full.source,
  note: `keyboard subset: ${words.length} words (top ${WORD_LIMIT} by freq) + ${full.chars.length} chars, generated by tools/build-keyboard-lexicon.mjs`,
  chars: full.chars,
  words,
}

mkdirSync(outDir, { recursive: true })
writeFileSync(outPath, JSON.stringify(trimmed), 'utf8')

const fullBytes = statSync(fullPath).size
const outBytes = statSync(outPath).size
const pct = ((outBytes / fullBytes) * 100).toFixed(1)

console.log(`chars: ${trimmed.chars.length}`)
console.log(`words: ${trimmed.words.length} (from ${full.words.length})`)
console.log(`size : ${(outBytes / 1024 / 1024).toFixed(2)} MB / ${(fullBytes / 1024 / 1024).toFixed(2)} MB (${pct}%)`)
console.log(`-> ${outPath}`)
